JOINTS = []            # (номер, лист, место, размер, прокладка)


def J(sh, sheet_no, x, y, orient, size, gasket, where, side=1, w=None):
    n = f'{sheet_no}{sum(1 for j in JOINTS if j[1] == sheet_no) + 1:02d}'
    JOINTS.append((n, sheet_no, where, size, gasket))
    sh.clamp(x, y, orient, n, side, w)
    return n


def JR(sh, x, y, orient, where, side=1, w=None):
    """Соединение уже учтено на другом листе — только показать его номер."""
    n = next(j[0] for j in JOINTS if j[2] == where)
    sh.clamp(x, y, orient, n, side, w)
    return n


def notes(sh, x, y, title, lines, size=2.3, step=3.9, width=None):
    sh.text(x, y, title, 2.8, bold=True)
    yy = y + 5.5
    for ln in lines:
        sh.text(x, yy, ln, size)
        yy += step
    return yy


def pipe(sh, pts, lw=0.9, color=INK, dash=None):
    sh.poly(pts, lw=lw, color=color, dash=dash)


def tube(sh, pts):          # трубка PTFE / нерж. малого диаметра
    sh.poly(pts, lw=0.45, color='#333333')


def hose(sh, pts):          # гибкий рукав
    sh.poly(pts, lw=0.9, color='#333333', dash='dash')


